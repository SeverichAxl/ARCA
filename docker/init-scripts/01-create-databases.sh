#!/usr/bin/env bash
set -euo pipefail

: "${AUTH_DB_PASSWORD:?AUTH_DB_PASSWORD es obligatorio}"
: "${PERSONAL_DB_PASSWORD:?PERSONAL_DB_PASSWORD es obligatorio}"
: "${VACACIONES_DB_PASSWORD:?VACACIONES_DB_PASSWORD es obligatorio}"
: "${CONTRATOS_DB_PASSWORD:?CONTRATOS_DB_PASSWORD es obligatorio}"
: "${PLANILLAS_DB_PASSWORD:?PLANILLAS_DB_PASSWORD es obligatorio}"

psql -v ON_ERROR_STOP=1 --username "${POSTGRES_USER}" --dbname "${POSTGRES_DB}" <<-EOSQL
  CREATE ROLE arca_auth LOGIN PASSWORD '${AUTH_DB_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE;
  CREATE DATABASE arca_auth OWNER arca_auth;

  CREATE ROLE arca_personal LOGIN PASSWORD '${PERSONAL_DB_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE;
  CREATE DATABASE arca_personal OWNER arca_personal;

  CREATE ROLE arca_vacaciones LOGIN PASSWORD '${VACACIONES_DB_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE;
  CREATE DATABASE arca_vacaciones OWNER arca_vacaciones;

  CREATE ROLE arca_contratos LOGIN PASSWORD '${CONTRATOS_DB_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE;
  CREATE DATABASE arca_contratos OWNER arca_contratos;

  CREATE ROLE arca_planillas LOGIN PASSWORD '${PLANILLAS_DB_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE;
  CREATE DATABASE arca_planillas OWNER arca_planillas;
EOSQL

echo "Bases de datos y roles de ARCA creados correctamente."
